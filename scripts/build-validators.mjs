// Precompiles the JSON Schema into a standalone validator so no code is generated at runtime
// (keeps a strict Content-Security-Policy possible). Runs before dev, test and build.
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const schemas = [{ file: 'public/schemas/teto-plan.v1.schema.json', out: 'validate-plan' }];

mkdirSync('src/generated', { recursive: true });
for (const { file, out } of schemas) {
  // Descriptions are documentation for people and AIs; strip them from the shipped validator.
  const schema = JSON.parse(readFileSync(file, 'utf8'), (key, value) =>
    // Only drop annotation strings, never a property *named* "description" (its value is a schema object).
    (key === 'description' || key === 'title') && typeof value === 'string' ? undefined : value,
  );
  const ajv = new Ajv2020({ allErrors: true, strict: true, strictRequired: false, code: { source: true, esm: true } });
  const validate = ajv.compile(schema);
  // Ajv's standalone output still `require`s two tiny runtime helpers; inline them so the
  // file is plain browser ESM with zero imports.
  const helpers = {
    'ajv/dist/runtime/ucs2length': '((s) => Array.from(s).length)',
    'ajv/dist/runtime/equal': '((a, b) => JSON.stringify(a) === JSON.stringify(b))',
  };
  let code = standaloneCode(ajv, validate).replace(/require\("([^"]+)"\)\.default/g, (_, mod) => {
    if (!helpers[mod]) throw new Error(`Unexpected Ajv runtime import: ${mod}`);
    return helpers[mod];
  });
  if (/require\(/.test(code)) throw new Error('Generated validator still contains require()');
  writeFileSync(`src/generated/${out}.js`, `// Generated by scripts/build-validators.mjs from ${file}. Do not edit.\n${code}\n`);
  writeFileSync(
    `src/generated/${out}.d.ts`,
    `import type { ErrorObject } from 'ajv';\ndeclare const validate: ((data: unknown) => boolean) & { errors?: ErrorObject[] | null };\nexport default validate;\n`,
  );
  console.log(`validator: ${file} -> src/generated/${out}.js`);
}
